E = html.escape


def load_js(path, var):
    """Чете window.<var> от JS файл чрез Node (без да изпълнява нищо друго от сайта)."""
    code = f"""
const vm = require('vm'); const fs = require('fs');
const ctx = {{ window: {{}} }}; vm.createContext(ctx);
vm.runInContext(fs.readFileSync({json.dumps(path)}, 'utf8'), ctx);
process.stdout.write(JSON.stringify(ctx.window[{json.dumps(var)}] ?? null));
"""
    out = subprocess.run(["node", "-e", code], capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def eur(n):
    if n is None:
        return "при запитване"
    s = f"{n:,.2f}".replace(",", " ").replace(".", ",")
    return (s[:-3] if s.endswith(",00") else s) + " €"


def prepare_dist():
    if os.path.isdir(DIST):
        if not os.path.exists(os.path.join(DIST, MARK)):
            sys.exit(f"Папката {DIST} не е създадена от този скрипт – няма да я изтрия.")
        shutil.rmtree(DIST)
    os.makedirs(DIST)
    open(os.path.join(DIST, MARK), "w").write("generated by tools/build_dist.py\n")

    def link_or_copy(src, dst, *, follow_symlinks=True):
        try:
            os.link(src, dst)
        except OSError:
            shutil.copy2(src, dst)
    # HTML и малките файлове се КОПИРАТ (не се свързват), защото index.html в dist се презаписва
    for f in ["index.html", "admin.html", "manifest.webmanifest", "sw.js", "_headers", "favicon.png"]:
        shutil.copy2(os.path.join(ROOT, f), os.path.join(DIST, f))
    shutil.copytree(os.path.join(ROOT, "assets"), os.path.join(DIST, "assets"), copy_function=link_or_copy)


def asset_versions():
    """Кратък отпечатък на всеки JS/CSS файл – добавя се като ?v=… към адреса, за да не ползва браузърът стар кеш след публикуване."""
    import hashlib
    out = {}
    d = os.path.join(ROOT, "assets")
    for f in os.listdir(d):
        if f.endswith((".js", ".css")):
            out[f] = hashlib.md5(open(os.path.join(d, f), "rb").read()).hexdigest()[:10]
    return out


def stamp(text, ver):
    return re.sub(r'(assets/)([\w.-]+\.(?:js|css))(?=["\'])', lambda m: f"{m.group(1)}{m.group(2)}?v={ver[m.group(2)]}" if m.group(2) in ver else m.group(0), text)


def rewrite(path, text):
    # файловете в dist може да са твърди връзки към изходните – пишем нов файл, а не върху връзката
    if os.path.exists(path):
        os.unlink(path)
    open(path, "w", encoding="utf-8").write(text)


def live_overrides(site):
    """Взема настройките от админ панела на живия сайт (скрити продукти и редакции на име/описание/снимки),
    за да ги отрази и в статичните страници за Google. Без връзка – празни настройки."""
    if "--offline" in sys.argv:
        return {}
    import ssl, urllib.request
    ctx = ssl.create_default_context(cafile="/root/.ccr/ca-bundle.crt") if os.path.exists("/root/.ccr/ca-bundle.crt") else None
    try:
        with urllib.request.urlopen(site + "/api/settings", timeout=15, context=ctx) as r:
            return json.load(r) or {}
    except Exception as e:
        print("(настройките от живия сайт не са достъпни:", str(e)[:80], ")")
        return {}


def apply_overrides(catalog, o):
    hidden = set(o.get("hidden") or []) | set(o.get("deleted") or [])
    ed = o.get("edits") or {}
    ok = lambda u: isinstance(u, str) and re.match(r"^(media/[a-z0-9]+\.(webp|jpg|png)|https://\S+)$", u)
    catalog["groups"] = [g for g in catalog["groups"] if g["s"] not in hidden]
    catalog["items"] = [i for i in catalog["items"] if i["s"] not in hidden]
    n = 0
    for g in catalog["groups"]:
        e = ed.get(g["s"])
        if not e: continue
        n += 1
        if (e.get("n") or "").strip(): g["n"] = e["n"].strip()
        if (e.get("d") or "").strip(): g["d"] = e["d"].strip()
        gal = [u for u in (e.get("gal") or []) if ok(u)]
        for v in g["v"]:
            vi = (e.get("vimg") or {}).get(str(v[0]))
            if ok(vi): v[6] = vi
            elif ok(e.get("img")): v[6] = e["img"]
            if gal: v[10] = gal
    for i in catalog["items"]:
        e = ed.get(i["s"])
        if not e: continue
        n += 1
        if (e.get("n") or "").strip(): i["n"] = e["n"].strip()
        if (e.get("d") or "").strip(): i["d"] = e["d"].strip()
        if ok(e.get("img")): i["im"] = e["img"]
    if n or hidden:
        print(f"от админ панела: {n} редактирани и {len(hidden)} скрити продукта")


