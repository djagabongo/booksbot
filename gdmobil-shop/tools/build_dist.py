#!/usr/bin/env python3
"""
Сглобява готовия за публикуване сайт в папка dist/:
  - копира статичните файлове (index.html, admin.html, assets/, manifest, sw.js, _headers)
  - генерира отделни HTML страници за Google за всеки продукт, категория,
    сервиза и правните текстове (с истинско съдържание, мета данни и JSON-LD)
  - генерира sitemap.xml и robots.txt

Употреба:  python3 tools/build_dist.py [--site https://gdmobil.netlify.app]
Изисква Node.js (за прочитане на assets/data.js).
"""
import html
import json
import os
import re
import shutil
import subprocess
import sys
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(ROOT, "dist")
MARK = ".gdm-dist"
E = html.escape


def load_js(path, var):
    """Чете window.<var> от JS файл чрез Node (без да изпълнява нищо друго от сайта)."""
    code = f"""
const vm = require('vm'); const fs = require('fs');
const ctx = {{ window: {{}} }}; vm.createContext(ctx);
vm.runInContext(fs.readFileSync({json.dumps(path)}, 'utf8'), ctx);
process.stdout.write(JSON.stringify(ctx.window[{json.dumps(var)}] ?? null));
"""
    out = subprocess.run(["node", "-e", code], capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def eur(n):
    if n is None:
        return "при запитване"
    s = f"{n:,.2f}".replace(",", " ").replace(".", ",")
    return (s[:-3] if s.endswith(",00") else s) + " €"


def prepare_dist():
    if os.path.isdir(DIST):
        if not os.path.exists(os.path.join(DIST, MARK)):
            sys.exit(f"Папката {DIST} не е създадена от този скрипт – няма да я изтрия.")
        shutil.rmtree(DIST)
    os.makedirs(DIST)
    open(os.path.join(DIST, MARK), "w").write("generated by tools/build_dist.py\n")

    def link_or_copy(src, dst, *, follow_symlinks=True):
        try:
            os.link(src, dst)
        except OSError:
            shutil.copy2(src, dst)
    # HTML и малките файлове се КОПИРАТ (не се свързват), защото index.html в dist се презаписва
    for f in ["index.html", "admin.html", "manifest.webmanifest", "sw.js", "_headers"]:
        shutil.copy2(os.path.join(ROOT, f), os.path.join(DIST, f))
    shutil.copytree(os.path.join(ROOT, "assets"), os.path.join(DIST, "assets"), copy_function=link_or_copy)


def main():
    site = None
    if "--site" in sys.argv:
        site = sys.argv[sys.argv.index("--site") + 1]
    store = load_js(os.path.join(ROOT, "assets", "data.js"), "STORE")
    cats = load_js(os.path.join(ROOT, "assets", "data.js"), "CATEGORIES")
    repairs = load_js(os.path.join(ROOT, "assets", "data.js"), "REPAIRS")
    catalog = load_js(os.path.join(ROOT, "assets", "catalog.js"), "CATALOG")
    specs = load_js(os.path.join(ROOT, "assets", "specs.js"), "SPECS")
    legal = load_js(os.path.join(ROOT, "assets", "legal.js"), "LEGAL")
    site = (site or store.get("siteUrl") or "https://gdmobil.netlify.app").rstrip("/")
    cat_names = {c["key"]: c["name"] for c in cats}
    no_thumb = set(catalog.get("noThumb", []))

    def img(h, big=True):
        if not h:
            return "assets/img/camera.svg"
        if h.startswith("assets/") or h.startswith("https:"):
            return h
        return f"assets/img/products/{h}.webp" if big or h in no_thumb else f"assets/img/products/{h}-sm.webp"

    prepare_dist()
    template = open(os.path.join(ROOT, "index.html"), encoding="utf-8").read()

    def page(path, title, desc, body, ld=None, image=None):
        url = f"{site}{path}"
        head = template
        head = head.replace("<head>", '<head>\n  <base href="/" />', 1)
        head = re.sub(r"<title>.*?</title>", f"<title>{E(title)}</title>", head, count=1, flags=re.S)
        head = re.sub(r'<meta name="description" content="[^"]*" />', f'<meta name="description" content="{E(desc)}" />', head, count=1)
        head = re.sub(r'<meta property="og:title" content="[^"]*" />', f'<meta property="og:title" content="{E(title)}" />', head, count=1)
        head = re.sub(r'<meta property="og:description" content="[^"]*" />', f'<meta property="og:description" content="{E(desc)}" />', head, count=1)
        og = image if image and image.startswith("https:") else site + "/" + (image or "assets/img/logo.webp")
        head = re.sub(r'<meta property="og:image" content="[^"]*" />', f'<meta property="og:image" content="{E(og)}" />', head, count=1)
        extra = f'  <link rel="canonical" href="{E(url)}" />\n  <meta property="og:url" content="{E(url)}" />\n'
        if ld:
            extra += f'  <script type="application/ld+json">{json.dumps(ld, ensure_ascii=False)}</script>\n'
        head = head.replace("</head>", extra + "</head>", 1)
        head = head.replace('<main id="view" tabindex="-1"></main>', f'<main id="view" tabindex="-1">{body}</main>', 1)
        out = os.path.join(DIST, path.strip("/"), "index.html") if path != "/" else os.path.join(DIST, "index.html")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        if os.path.exists(out):
            os.unlink(out)  # никога не пишем през връзка към изходен файл
        open(out, "w", encoding="utf-8").write(head)
        return url

    urls = []
    crumbs = lambda items: '<nav class="crumbs" aria-label="Навигация"><a href="/">Начало</a>' + "".join(
        f' <span>/</span> <a href="{E(h)}">{E(t)}</a>' if h else f' <span>/</span> <span aria-current="page">{E(t)}</span>' for t, h in items) + "</nav>"

    # ---------- продукти ----------
    products = []
    for g in catalog["groups"]:
        variants = [{"id": v[0], "storage": v[1], "ram": v[2], "color": v[3], "conn": v[4], "price": v[5], "img": v[6]} for v in g["v"]]
        products.append({"slug": g["s"], "name": g["n"], "brand": g["b"], "cat": g["c"], "variants": variants, "specs": g.get("sp", {}), "img": variants[0]["img"]})
    for i in catalog["items"]:
        products.append({"slug": i["s"], "name": i["n"], "brand": i["b"], "cat": i["c"], "sub": i.get("sc", ""), "compat": i.get("cm", []),
                         "variants": [{"id": i["i"], "storage": "", "ram": "", "color": "", "conn": "", "price": i["p"], "img": i["im"]}], "specs": {}, "img": i["im"]})
    model_names = {m["key"]: f'{m["brand"]} {m["name"]}' for m in catalog["models"]}

    for p in products:
        priced = [v["price"] for v in p["variants"] if v["price"] is not None]
        lo = min(priced) if priced else None
        hi = max(priced) if priced else None
        cat = cat_names.get(p["cat"], "")
        many = len(p["variants"]) > 1
        price_txt = (("от " if many else "") + eur(lo)) if lo is not None else "Цена при запитване"
        desc = f'{p["name"]} – {price_txt} с ДДС. {"Избери памет и цвят, п" if many else "П"}оръчай онлайн или вземи от GDMobil в Гоце Делчев.'
        rows = []
        for title, sec in (specs.get(p["slug"]) or ([["Характеристики", list(p["specs"].items())]] if p["specs"] else [])):
            rows.append(f'<section class="specbox"><h3>{E(title)}</h3><dl>' + "".join(f"<div><dt>{E(k)}</dt><dd>{E(str(v))}</dd></div>" for k, v in sec) + "</dl></section>")
        var_list = ""
        if many:
            var_list = "<h2>Конфигурации и цени</h2><ul class=\"seo-list\">" + "".join(
                f'<li>{E(" · ".join(x for x in [v["storage"], v["ram"] and v["ram"] + " RAM", v["color"], v["conn"]] if x) or "Стандартна")} – <b>{E(eur(v["price"]))}</b></li>'
                for v in p["variants"]) + "</ul>"
        compat = ""
        if p.get("compat"):
            compat = "<h2>Съвместим с</h2><p>" + ", ".join(E(model_names.get(k, k)) for k in p["compat"]) + "</p>"
        body = f'''<section class="container page seo-pre">{crumbs([(cat, f"/c/{p['cat']}/"), (p["name"], None)])}
<div class="pd"><div class="pd__gallery"><div class="pd__main"><div class="pd__stage"><img src="{E(img(p["img"]))}" alt="{E(p["name"])}" width="600" height="600"></div></div></div>
<div class="pd__info"><div class="pd__brand"><span>{E(p["brand"])} / {E(cat)}{(" / " + E(p.get("sub"))) if p.get("sub") else ""}</span></div><h1>{E(p["name"])}</h1>
<div class="pd__buy"><div class="pd__price"><span class="price">{E(price_txt)}</span><small class="muted">с ДДС</small></div><p class="stock"><i></i>В наличност</p>
<a class="btn btn--primary btn--lg btn--block" href="#/p/{p["slug"]}">Избери и поръчай</a></div>{var_list}{compat}</div></div>
{f'<div class="pd-section"><h2>Технически характеристики</h2><div class="specgrid">{"".join(rows)}</div></div>' if rows else ""}</section>'''
        ld = {"@context": "https://schema.org", "@type": "Product", "name": p["name"], "brand": {"@type": "Brand", "name": p["brand"]},
              "image": img(p["img"]) if img(p["img"]).startswith("https:") else f'{site}/{img(p["img"])}', "sku": str(p["variants"][0]["id"]), "category": cat, "url": f'{site}/p/{p["slug"]}/'}
        if lo is not None:
            ld["offers"] = {"@type": "AggregateOffer", "priceCurrency": "EUR", "lowPrice": lo, "highPrice": hi, "offerCount": len(priced),
                            "availability": "https://schema.org/InStock", "seller": {"@type": "Organization", "name": "GDMobil"}}
        urls.append(page(f'/p/{p["slug"]}/', f'{p["name"]} – {price_txt} | GDMobil', desc, body, ld, img(p["img"])))

    # ---------- категории ----------
    for c in cats:
        items = sorted([p for p in products if p["cat"] == c["key"]], key=lambda p: (p["brand"].lower(), p["name"].lower()))
        by_brand = {}
        for p in items:
            by_brand.setdefault(p["brand"], []).append(p)
        lists = "".join(f'<h2>{E(b)} ({len(ps)})</h2><ul class="seo-list seo-list--cols">' + "".join(
            f'<li><a href="/p/{p["slug"]}/">{E(p["name"])}</a> – {E(("от " if len(p["variants"]) > 1 else "") + eur(min([v["price"] for v in p["variants"] if v["price"] is not None], default=None)))}</li>' for p in ps) + "</ul>"
            for b, ps in by_brand.items())
        body = f'''<section class="container page seo-pre">{crumbs([(c["name"], None)])}<div class="cat-head"><h1>{E(c["name"])}</h1><p class="muted">{len(items)} продукта · {E(c["sub"])}</p></div>
<p><a class="btn btn--primary" href="#/c/{c["key"]}">Разгледай с филтри</a></p>{lists}</section>'''
        ld = {"@context": "https://schema.org", "@type": "CollectionPage", "name": f'{c["name"]} | GDMobil', "url": f'{site}/c/{c["key"]}/'}
        urls.append(page(f'/c/{c["key"]}/', f'{c["name"]} – {c["sub"]} | GDMobil Гоце Делчев', f'{c["name"]} в GDMobil: {len(items)} продукта с цени в евро. Поръчай онлайн или вземи от магазина в Гоце Делчев.', body, ld))

    # ---------- сервиз ----------
    rep = "".join(f'<li><b>{E(r["title"])}</b> – {E(r["price"])}. {E(r["text"])}</li>' for r in repairs)
    body = f'''<section class="container page seo-pre">{crumbs([("Сервиз", None)])}<h1>Сервиз за телефони и таблети в Гоце Делчев</h1>
<p>Смяна на дисплеи и батерии, ремонт на букси за зареждане, камери и бутони, софтуер и диагностика. Цените са ориентировъчни – точната сума се уточнява след преглед.</p>
<ul class="seo-list">{rep}</ul><p><a class="btn btn--primary" href="#/service">Запитване за ремонт</a></p></section>'''
    ld = {"@context": "https://schema.org", "@type": "Service", "serviceType": "Ремонт на телефони и таблети", "areaServed": "Гоце Делчев",
          "provider": {"@type": "MobilePhoneStore", "name": "GDMobil", "telephone": store.get("phoneIntl"), "address": store.get("address")}}
    urls.append(page("/service/", "Сервиз за телефони и таблети – цени | GDMobil Гоце Делчев", "Ремонт на телефони и таблети в Гоце Делчев: дисплей от 30 €, батерия от 30 €, букса от 15 €. Оферта преди ремонта.", body, ld))

    # ---------- правни страници ----------
    for key, d in legal.items():
        secs = "".join(f'<section><h2>{E(s["h"])}</h2>' + "".join(f"<p>{E(x)}</p>" for x in s["p"]) + "</section>" for s in d["sections"])
        body = f'<section class="container page seo-pre">{crumbs([(d["title"], None)])}<article class="legal__body"><h1>{E(d["title"])}</h1><p class="lead muted">{E(d["intro"])}</p>{secs}</article></section>'
        urls.append(page(f"/legal/{key}/", f'{d["title"]} | GDMobil', d["intro"], body))

    # ---------- начална страница (съдържание за Google, което SPA подменя) ----------
    featured = [p for s in store.get("featured", []) for p in products if p["slug"] == s]
    body = f'''<section class="container page seo-pre"><h1>GDMobil – телефони, аксесоари и сервиз в Гоце Делчев</h1>
<p>{E(store.get("tagline", ""))} Избери памет и цвят, поръчай онлайн с доставка до офис или адрес, или вземи от магазина без такса.</p>
<h2>Категории</h2><ul class="seo-list">{"".join(f'<li><a href="/c/{c["key"]}/">{E(c["name"])}</a> – {E(c["sub"])}</li>' for c in cats)}<li><a href="/service/">Сервиз за телефони и таблети</a></li></ul>
<h2>Подбрани смартфони</h2><ul class="seo-list">{"".join(f'<li><a href="/p/{p["slug"]}/">{E(p["name"])}</a></li>' for p in featured)}</ul>
<p>{E(store.get("address", ""))} · {E(store.get("phone", ""))} · {E(store.get("email", ""))}</p></section>'''
    ld = {"@context": "https://schema.org", "@type": "MobilePhoneStore", "name": "GDMobil", "url": site + "/", "telephone": store.get("phoneIntl"), "email": store.get("email"),
          "address": {"@type": "PostalAddress", "streetAddress": "ул. „Солун“ 21", "addressLocality": "Гоце Делчев", "postalCode": store.get("postcode", "2900"), "addressCountry": "BG"},
          "openingHours": ["Mo-Fr 09:30-18:00", "Sa 10:00-14:00"], "sameAs": [v for v in store.get("social", {}).values() if v]}
    home = page("/", "GDMobil — Телефони, аксесоари и сервиз в Гоце Делчев", "Телефони, таблети, аксесоари и камери с цени в евро. Поръчай онлайн или вземи от GDMobil в Гоце Делчев. Сервиз за телефони и таблети.", body, ld)
    urls.insert(0, home)

    # ---------- sitemap и robots ----------
    today = date.today().isoformat()
    sm = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    sm += [f"  <url><loc>{E(u)}</loc><lastmod>{today}</lastmod></url>" for u in urls]
    sm.append("</urlset>")
    open(os.path.join(DIST, "sitemap.xml"), "w", encoding="utf-8").write("\n".join(sm) + "\n")
    open(os.path.join(DIST, "robots.txt"), "w").write(f"User-agent: *\nAllow: /\nDisallow: /admin.html\nDisallow: /api/\n\nSitemap: {site}/sitemap.xml\n")
    print(f"dist: {len(urls)} страници (продукти: {len(products)}), sitemap.xml, robots.txt · сайт: {site}")


if __name__ == "__main__":
    main()
